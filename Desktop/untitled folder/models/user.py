from extensions import db
from flask_login import UserMixin
from datetime import datetime

class User(UserMixin, db.Model):
    __tablename__ = 'users'

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(80), unique=True, nullable=False)
    email = db.Column(db.String(120), unique=True, nullable=False)
    password = db.Column(db.String(200), nullable=False)
    role = db.Column(db.String(20), nullable=False)  # 'HR', 'Manager', 'Employee'
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    goals = db.relationship('Goal', backref='owner', lazy=True)
    competencies = db.relationship('Competency', backref='owner', lazy=True)
    performance_documents = db.relationship('PerformanceDocument', backref='owner', lazy=True)
    evaluations = db.relationship('Evaluation', backref='employee', lazy=True)
    notifications = db.relationship('Notification', backref='recipient', lazy=True)

    def to_dict(self):
        return {
            'id': self.id,
            'username': self.username,
            'email': self.email,
            'role': self.role,
            'created_at': self.created_at.isoformat(),
            'updated_at': self.updated_at.isoformat()
        }